def convert_to_str(clusters):
    lines = []
    num_1 = 1
    for k, v in clusters.items():
        lines.append(str(k))
        num_2 = 1
        for item in v:
            lines.append(f"{num_1}.{num_2} - {item}")
            num_2 += 1
        num_1 += 1
    return "\n".join(lines)


